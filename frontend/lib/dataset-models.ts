// ==========================================
// Dataset Models & Narrative Configurations
// ==========================================

export interface ColumnDefinition {
  name: string
  isAiPick: boolean
  reason: string
  dataType: "date" | "category" | "numeric" | "identifier"
}

export interface MetricCard {
  label: string
  value: string
  badge: string
  isWarm?: boolean
}

export interface TrendPoint {
  x: number // svg coordinate 40 to 460
  y: number // svg coordinate
  label: string
  val: number
  displayVal: string
  isPeak?: boolean
}

export interface BarItem {
  name: string
  val: number // percentage 0-100 or metric
  displayVal: string
  isWarm?: boolean
}

export interface DonutSegment {
  name: string
  share: number // e.g. 52
  color: string
  isPrimary?: boolean
  isWarm?: boolean
}

export interface BoxPlotData {
  min: number
  q1: number
  median: number
  q3: number
  max: number
  outlierValue: number
  outlierLabel: string
  unit: string
}

export interface ScatterPoint {
  x: number // 0-100 percentage in svg
  y: number // 0-100 percentage in svg
  name: string
  xVal: string
  yVal: string
}

export interface StoryBoardConfig {
  datasetTitle: string
  analysisTitle: string
  chartExplanation?: string
  takeawayMessage?: string
  primaryChart: string
  altChart: string
  swapRule: string
  metrics: MetricCard[]
  insights: string[]
  trendData?: TrendPoint[]
  barData?: BarItem[]
  donutData?: DonutSegment[]
  boxPlotData?: BoxPlotData
  scatterData?: ScatterPoint[]
  histogramBars?: number[]
}

export interface AnalyticalGoalBundle {
  id: string
  title: string
  question: string
  targetColumns: string[]
  recommendedAnalysis: string
  badge?: string
}

export interface ColumnCombinationInsight {
  analysisMethod: string
  headline: string
  explanation: string
  questionAnswered: string
  suitableCharts: string[]
  columnCount: number
}

export interface DatasetMeta {
  id: string
  backendId?: number // dataset_id in the Flask backend (set for real uploads)
  name: string
  size: string
  type: string
  rowCount: number
  colCount: number
  desc: string
  recommendedAnalysisId: string
  analysisReason: string
  columns: ColumnDefinition[]
  goalBundles?: AnalyticalGoalBundle[]
}

